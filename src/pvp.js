// Правила PvP (общие для клиента и сервера): флаг, карма, отмыв, стражи.
export const PVP = {
  damageScale: 0.30,       // более длинные дуэли; одинаково для прямого урона и DoT
  flagMs: 30_000,          // сколько длится флаг после удара по «белому»
  minHitMs: 250,           // не чаще одного удара по игроку
  karmaPerXp: 4,           // опыт моба / 4 = сколько кармы смывается
  announceMs: 60_000,      // объявление о PK на весь сервер
  guardRange: 22,          // стражи у ворот видят PK
  guardHit: 0.22,          // доля здоровья за удар стража
  dropChance: 0.5,         // шанс уронить вещь при смерти PK
  atkCap: (lvl) => 40 + Math.max(1, lvl) * 12,  // потолок атаки, которую сервер пропустит
};
// карма растёт с каждым новым PK
export const karmaForPk = (pk) => 360 + (Math.max(1, pk) - 1) * 180;
// отмыв у жреца: 5 монет за единицу кармы
export const karmaWashCost = (karma) => Math.ceil(karma) * 5;
