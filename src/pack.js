// Стаи: семейства мобов и помощь сородичей. Без DOM — чистые функции, проверяются юнит-тестами.
// Атака по одному мобу поднимает соседей того же семейства в радиусе SOCIAL_R.

// 12 единиц текущего масштаба мира (человек 2.5): меньше радиуса агрессии 14,
// поэтому стая подтягивается ближним кругом, а не всей поляной.
export const SOCIAL_R = 12;

// Семейство: явное поле fam в определении моба, иначе вид. Разные виды одного fam помогают друг другу.
export const famOf = (m) => m.def?.fam || m.kind;

// Мобы охотничьих лагерей из стай исключены: стартовые группы за воротами остаются щадящими.
export const social = (m) => !!m.def?.social && !m.camp && !m.def?.boss;

// Кто вступится за m: живые сородичи того же семейства в радиусе, ещё не втянутые в бой.
export function socialAllies(m, list, r = SOCIAL_R) {
  if (!social(m)) return [];
  const fam = famOf(m);
  return list.filter((o) => o !== m && !o.dead && social(o) && famOf(o) === fam
    && o.state !== 'chase' && o.state !== 'return'
    && Math.hypot(o.x - m.x, o.z - m.z) <= r);
}
